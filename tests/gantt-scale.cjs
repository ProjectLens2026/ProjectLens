const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),ts=require('typescript')
const out={};vm.runInNewContext(ts.transpileModule(fs.readFileSync(require('node:path').join(__dirname,'../src/lib/ganttScale.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:out})
const min=Date.parse('2028-01-15T00:00:00Z'),max=Date.parse('2028-04-15T00:00:00Z')
assert.equal(out.ganttScale(min,max,'fit').width,420)
assert.ok(out.ganttScale(min,max,'day').width>out.ganttScale(min,max,'week').width)
assert.equal(new Date(out.ganttScale(min,max,'month').ticks[1].time).toISOString(),'2028-03-01T00:00:00.000Z')
assert.equal(out.ganttScale(min,max,'quarter').ticks[0].label,'Q2 2028')
assert.ok(out.ganttScale(min,min,'day').span>0)
console.log('PASS: fit, zoom widths, month boundaries, leap year, quarter and zero-duration range')
